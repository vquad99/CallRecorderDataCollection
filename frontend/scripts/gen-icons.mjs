// Generates src/components/icons.generated.ts from Phosphor Icons (MIT, @phosphor-icons/react):
// only the icons and weights the app uses, as plain path data. Phosphor ships every icon in six
// weights inside one component (about 1-3 KB compressed each); the app needs two, so the full
// package would cost the first screen about 25 KB.  Run: node scripts/gen-icons.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ICONS = {
  chart: "ChartBar",
  projects: "FolderSimple",
  tasks: "ListChecks",
  users: "UsersThree",
  settings: "GearSix",
  audit: "ShieldCheck",
  status: "Pulse",
  logout: "SignOut",
  menu: "List",
  close: "X",
  mic: "Microphone",
  verified: "SealCheck",
  lock: "LockKey",
  plus: "Plus",
  search: "MagnifyingGlass",
  warning: "WarningCircle",
  ok: "CheckCircle",
  failed: "XCircle",
  empty: "Tray",
  next: "CaretRight",
  previous: "CaretLeft",
  waveform: "Waveform",
  upload: "Upload",
  stop: "Stop",
  play: "Play",
};
// Every icon gets "regular"; these also get the weights they are shown in.
const EXTRA = {
  plus: ["bold"],
};

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const pkg = dirname(require.resolve("@phosphor-icons/react/package.json"));

function paths(element) {
  const out = [];
  const walk = (node) => {
    if (!node || typeof node !== "object") return;
    if (Array.isArray(node)) return node.forEach(walk);
    if (node.type === "path" && node.props?.d) out.push(node.props.d);
    walk(node.props?.children);
  };
  walk(element);
  return out;
}

const lines = [];
for (const [name, component] of Object.entries(ICONS)) {
  const mod = await import(pathToFileURL(join(pkg, "dist/defs", `${component}.es.js`)).href);
  const weights = Object.values(mod).find((v) => v instanceof Map);
  const entry = {};
  for (const w of ["regular", ...(EXTRA[name] ?? [])]) {
    const d = paths(weights.get(w));
    if (d.length === 0) throw new Error(`${component}: no ${w} path`);
    entry[w] = d.join(" ");
  }
  lines.push(`  ${name}: ${JSON.stringify(entry)},`);
}
writeFileSync(
  join(here, "../src/components/icons.generated.ts"),
  `// GENERATED by scripts/gen-icons.mjs from Phosphor Icons (MIT, https://phosphoricons.com).\n` +
    `// Do not edit by hand: add the icon to the script and run it again.\n` +
    `export const ICON_PATHS = {\n${lines.join("\n")}\n} as const;\n`,
);
console.log(`${Object.keys(ICONS).length} icons written`);
